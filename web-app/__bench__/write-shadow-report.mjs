import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const directory = process.argv[2];
if (!directory) throw new Error('Pass the unit results directory containing replay/*.json');
const rows = [];
let scenarios = 0;
let views = 0;
let fieldMismatches = 0;
for (const file of readdirSync(join(directory, 'replay')).sort()) {
  const reports = JSON.parse(readFileSync(join(directory, 'replay', file), 'utf8'));
  for (const report of reports) {
    scenarios += 1;
    views += report.views;
    const groups = new Map();
    for (const entry of report.differences) {
      for (const field of entry.fields) {
        fieldMismatches += 1;
        const key = JSON.stringify(field);
        const group = groups.get(key) ?? { ...field, observations: [] };
        group.observations.push(`${entry.store}:${entry.step}`);
        groups.set(key, group);
      }
    }
    if (groups.size) {
      rows.push(`### ${report.scenario}\n\nSuite: \`${file.replace(/\.json$/, '')}\`.\n\n| Field | Derived | Stored | Store:step | Attribution |\n| --- | --- | --- | --- | --- |`);
      for (const group of groups.values()) {
        const attribution = group.field === 'isMyTurn'
          ? 'Store bug: getter becomes a stale data property after Immer copies the state.'
          : 'Cursor contract gap. See the classification below; the store is not automatically wrong.';
        rows.push(`| \`${group.field}\` | \`${JSON.stringify(group.derived)}\` | \`${JSON.stringify(group.stored)}\` | ${group.observations.join(', ')} | ${attribution} |`);
      }
      rows.push('');
    }
  }
}
const preamble = `# Unit 4b shadow mismatches

Generated by \`node web-app/__bench__/write-shadow-report.mjs artifacts/agent-friendly-plan/units/u04b\` after a replay with \`DERIVE_SHADOW_REPORT_DIR\` set to that directory's \`replay/\` subdirectory.

The replay covers ${scenarios} scenarios and ${views} observed states. It found ${fieldMismatches} differing field observations. Every other field observation deep-equals the real store. The committed per-suite snapshots pin every exception by scenario, store number, notification step, field, and both values. A new exception fails. Steps include fixture setup and cleanup transitions, so a preceding scenario's cursor can appear until the next reset. Store numbers restart per scenario.

## Classification and ownership

- **Stored \`isMyTurn\` is a store bug.** Zustand evaluates the initial getter through Immer's state copy, leaving the original false value on later state objects. At a valid manager turn, the shadow returns true and the stored property stays false. At the time of this historical receipt, the production \`useIsMyTurn\` hook called \`calculateIsMyTurn\` directly, so this is a stale store property rather than proof of a visible turn-indicator defect. This PR preserves it.
- **Sparse provider imports require an explicit provider cursor source.** \`reconcileSyncedPicks\` accepts \`nextPickNumber\` even when earlier picks are missing or filtered out as preloaded keepers. The real store is right to honor that provider cursor in the existing contract. A first-open-slot derivation returns the earliest gap. Examples include linear keeper imports, provider overrides, the Rashee Rice/Omarion Hampton conflict, keeper deduplication, practice-rule changes, and direct imported picks. This is a missing source fact in the proposed unit-10 model, not a store bug. Unit 10 must retain provider progress as source data or explicitly change that contract. \`lastConfirmedPickNumber\` cannot replace the supplied cursor when no confirmed timestamp was given or keeper history was removed.
- **Branch cursors also require a source fact.** \`branchFromPick(96)\` can move an empty history to 96. The paired-store regression proves equal proposed source facts can yield stored cursors 1 and 96. Derivation from only those facts cannot preserve both. Consuming and undoing the isolated keeper then yields stored cursors 97 and 96 while the earliest gap stays 1. These are supported store transitions, not store bugs.
- **Mock keeper consumption is a separate phase.** A keeper is unavailable and already in its roster before \`consumeKeeperAtCurrentPick\` records it in history. The store intentionally pauses on its keeper slot, while the proposed occupied-slot policy skips it. The 10x14 replay gives derived/stored pairs 2/1, 71/70, and 141/140. Existing keeper-supply tests expose the same distinction at other keeper slots. Reset deliberately returns to pick 1 even with a round-one reservation. These are policy and phase gaps for unit 10, not proven store bugs. Preserve the phase as a source fact or define a mode-specific cursor rule before switching.
- **Direct \`setState({ currentPick: 4 })\` is test-only mutation.** The provider-scope test checks store isolation with no source history. Derived 1 versus stored 4 is expected and does not identify a production bug.

All roster, drafted-ID, and visible-shortlist comparisons pass. Unresolved provider picks reserve their slot without acquiring a guessed player or roster entry. The adapter reads the old store's surviving shortlist intent; it does not invent lost hidden intent. Independent pure tests retain the full ordered intent through provisional removal and correction. Preservation of intent across future reducer commands still belongs to unit 10.

No production action, state field, getter, or consumer changed. The exceptions expose assumptions that must be resolved before the real owner switch.

## Exact observed exceptions

`;
writeFileSync(join(directory, 'MISMATCHES.md'), (preamble + rows.join('\n')).trimEnd() + '\n');
console.log(JSON.stringify({ scenarios, views, fieldMismatches }));
