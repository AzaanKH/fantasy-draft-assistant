import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { COMMANDS } from '../cli/src/commands.ts';
import { catalogMetadata, catalogRetentionMetadata } from '../shared/src/catalog/manifest.ts';
import agentRules, { baselineRuleIds } from './agent-lint-rules.mjs';
import eslintConfig from '../eslint.config.js';
import { jsonAllowances, referenceImages, goldenSnapshots, sourceAssets, maxTrackedBytes } from './check-tracked-data.mjs';
import { maxPrFiles } from './check-pr-size.mjs';

const projectRoot = path.resolve(import.meta.dirname, '..');
const cell = value => String(value).replaceAll('|', '\\|').replaceAll('\n', ' ');
const code = value => `\`${value}\``;
const table = (headers, rows) => [headers, headers.map(() => '---'), ...rows]
  .map(row => `| ${row.map(cell).join(' | ')} |`).join('\n');

export function documentationSections({ commands = COMMANDS, catalog = catalogMetadata(), rules = agentRules.rules,
  retention = catalogRetentionMetadata(), baselineIds = baselineRuleIds, config = eslintConfig } = {}) {
  const commandRows = Object.entries(commands).flatMap(([name, command]) => {
    if (!command.help?.trim() || !command.examples?.length) throw new Error(`Command ${name} needs help and documentation examples in cli/src/commands.ts.`);
    return command.examples.map(example => {
      if (example.command.split(' ')[1] !== name || !example.task || !example.result) {
        throw new Error(`Command ${name} has an invalid documentation example in cli/src/commands.ts.`);
      }
      return [example.task, code(example.command), example.result];
    });
  });
  const paths = new Set();
  const catalogRows = catalog.map(entry => {
    if (!entry.path || paths.has(entry.path) || !['all', 'local', 'none'].includes(entry.browser) ||
        !['tracked', 'private'].includes(entry.classification) || !entry.source?.trim() || !entry.notes?.trim()) {
      throw new Error(`Catalog entry ${entry.path ?? '(missing path)'} needs unique path, browser, classification, source, and notes in shared/src/catalog/manifest.ts.`);
    }
    paths.add(entry.path);
    return [code(entry.path), entry.source, entry.notes, code(entry.browser), entry.classification];
  });
  const retentionRows = [
    ...retention.trackedPaths.map(path => [code(path), 'Exact path', 'tracked']),
    ...retention.privatePrefixes.map(path => [code(path), 'Prefix', 'private']),
  ];
  const ruleNames = Object.keys(rules).sort();
  const ruleRows = ruleNames.map(name => {
    const rule = rules[name];
    const id = `agent/${name}`;
    if (!rule.meta?.docs?.description?.trim()) throw new Error(`${id} needs meta.docs.description in scripts/agent-lint-rules.mjs.`);
    if (!rule.meta.docs.hint?.trim()) throw new Error(`${id} needs meta.docs.hint in scripts/agent-lint-rules.mjs.`);
    return [code(id), rule.meta.docs.description, rule.meta.docs.hint, baselineIds.includes(id) ? 'Occurrences in eslint-baseline.json' : 'No allowance'];
  });
  const scopes = ruleNames.map(name => {
    const id = `agent/${name}`;
    const blocks = config.filter(block => {
      const setting = block.rules?.[id];
      return ['error', 'warn', 1, 2].includes(Array.isArray(setting) ? setting[0] : setting);
    });
    if (!blocks.length) throw new Error(`${id} has no enabled config block in eslint.config.js.`);
    return `- ${code(id)} applies to ${blocks.map(block => `${(block.files ?? ['**/*']).map(code).join(', ')}${block.ignores?.length ? `, excluding ${block.ignores.map(code).join(', ')}` : ''}`).join('; ')}.`;
  }).join('\n');
  const ruleTable = table(['Rule', 'Enforced behavior', 'Fix hint', 'Baseline policy'], ruleRows);
  const notice = 'Generated by `pnpm docs:generate`. `pnpm docs:check` rejects drift.';
  return [
    { file: 'docs/cli.md', marker: 'cli-commands', content: `${notice}\n\n${table(['Task', 'Command', 'Result'], commandRows)}` },
    { file: 'docs/data-refresh.md', marker: 'data-catalog', content: `${notice}\n\nBrowser exposure is \`all\` for local and demo builds, \`local\` for local builds only, and \`none\` for neither.\n\n${table(['Artifact', 'Source', 'Notes', 'Browser', 'Retention'], catalogRows)}\n\nAdditional retention rules come from the same manifest. Exact tracked exceptions take precedence over private prefixes. Unknown paths and paths with empty, \`.\`, or \`..\` segments have no classification.\n\n${table(['Path', 'Match', 'Retention'], retentionRows)}` },
    { file: 'docs/workspace-gates.md', marker: 'repository-policy', content: `${notice}\n\nThe tracked-tree leak scan reads every Git-tracked regular file, including ASCII patterns in binary content. Tracked symlinks and unreadable files fail. Diagnostics redact matched content. Each existing allowance records a content fingerprint and a reason in \`tracked-leak-baseline.json\`; additional occurrences still fail.\n\nTracked files have a ${maxTrackedBytes}-byte limit, including catalog data and source files. The two exact reference artwork paths below have an ${8 * maxTrackedBytes}-byte limit. \`data/\` and \`demo-data/\` must have a tracked catalog classification. Other generated data kinds, raw exports, databases and binary assets fail outside the exact paths below. JSON outside these paths is limited to registered workspace package and TypeScript configuration files.\n\n${table(['Exact allowed path', 'Reason'], [...jsonAllowances, ...referenceImages, ...goldenSnapshots, ...sourceAssets].map(([file, reason]) => [code(file), reason]))}\n\nPR CI compares the event base and head using their merge base and rename detection. At most ${maxPrFiles} changed files are allowed; a rename counts once. Local use is \`pnpm check:pr-size --base <commit> --head <commit>\`. Without an event or explicit commits, it reports that size was not checked. The CI checkout fetches the complete commit graph.\n\nExtension builds check all four emitted UI roots and their static and dynamic chunk closure for Effect module identities. Classic content scripts must also be self-contained; the background worker may use Effect. Web data boundaries may use Effect. Built-package contracts check the emitted static and dynamic import closure of \`@fantasy-draft/shared/draft\` for Effect, including dormant dynamic imports. Node module-loader imports and getBuiltinModule access are rejected in this plain closure. Missing modules, nonliteral imports and unresolved nonbuiltin external dependencies fail closed. Run \`pnpm check:draft-effect\` after building shared; runtime contracts also keep \`/http\` Effect-free.` },
    { file: 'AGENTS.md', marker: 'agent-rules', content: `${notice}\n\nDescriptions come from each rule's \`meta.docs\`. Baseline eligibility comes from \`baselineRuleIds\` in \`scripts/agent-lint-rules.mjs\`.\n\n${ruleTable}` },
    { file: 'docs/workspace-gates.md', marker: 'workspace-rules', content: `${notice}\n\nThe lint wrapper allows exact occurrence fingerprints only for ${baselineIds.map(code).join(', ')}. All other rules have no baseline allowance. Rule visitors report violations independently of that wrapper.\n\n${ruleTable}\n\nThe following scopes come from \`eslint.config.js\`. Global ESLint ignores also apply.\n\n${scopes}` },
  ];
}

export function replaceGeneratedSection(document, { file, marker, content }) {
  const start = `<!-- generated:${marker}:start -->`;
  const end = `<!-- generated:${marker}:end -->`;
  if (document.split(start).length !== 2 || document.split(end).length !== 2 || document.indexOf(end) < document.indexOf(start)) {
    throw new Error(`${file} must contain exactly one ordered pair of ${start} and ${end}. Restore the markers before running pnpm docs:generate.`);
  }
  return document.slice(0, document.indexOf(start) + start.length) + `\n${content}\n` + document.slice(document.indexOf(end));
}

export async function generateDocs({ root = projectRoot, check = false } = {}) {
  const grouped = new Map();
  for (const section of documentationSections()) {
    const sections = grouped.get(section.file) ?? [];
    sections.push(section);
    grouped.set(section.file, sections);
  }
  const updates = await Promise.all([...grouped].map(async ([file, sections]) => {
    const target = path.join(root, file);
    let original;
    try { original = await readFile(target, 'utf8'); }
    catch (error) { throw new Error(`Cannot read ${file}. Restore the document and its generated markers.`, { cause: error }); }
    return { target, file, original, generated: sections.reduce((document, section) => replaceGeneratedSection(document, section), original) };
  }));
  const changed = updates.filter(update => update.original !== update.generated);
  if (check && changed.length) throw new Error(`Generated documentation drift in ${changed.map(update => update.file).join(', ')}. Run pnpm docs:generate and commit the updated sections.`);
  if (!check) await Promise.all(changed.map(update => writeFile(update.target, update.generated)));
  return changed.map(update => update.file);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    if (process.argv.slice(2).some(argument => argument !== '--check')) throw new Error('Usage: pnpm docs:generate [--check]');
    const changed = await generateDocs({ check: process.argv.includes('--check') });
    console.log(changed.length ? `Generated ${changed.join(', ')}.` : 'Generated documentation is current.');
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
